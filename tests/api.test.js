import {test} from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
process.env.DEMO_MODE='true';
delete process.env.MONGODB_URI;
const {default:app}=await import('../server/app.js');
const login=async role=>(await request(app).post('/api/auth/demo').send({role}).expect(200)).body.token;
const auth=(token)=>({Authorization:`Bearer ${token}`});
test('full workflow and server-side permissions',async()=>{
 const customer=await login('customer'),admin=await login('admin'),agent=await login('agent');
 await request(app).get('/api/tickets').expect(401);
 await request(app).get('/api/tickets/TK-1041').set(auth(customer)).expect(404);
 await request(app).post('/api/tickets/TK-1041/replies').set(auth(customer)).send({text:'unauthorized'}).expect(404);
 const attachment={name:'evidence.txt',type:'text/plain',data:'data:text/plain;base64,aGVsbG8='};
 const created=(await request(app).post('/api/tickets').set(auth(customer)).send({title:'Cannot open reports',description:'The report screen does not open after signing in.',priority:'High',category:'Technical',attachments:[attachment]}).expect(201)).body;
 const id=created._id;
 await request(app).get('/api/tickets/'+id).set(auth(agent)).expect(404);
 await request(app).patch('/api/tickets/'+id).set(auth(customer)).send({status:'Resolved'}).expect(403);
 await request(app).patch('/api/tickets/'+id).set(auth(admin)).send({assignee:'agent'}).expect(200);
 await request(app).patch('/api/tickets/'+id).set(auth(agent)).send({assignee:null}).expect(403);
 await request(app).patch('/api/tickets/'+id).set(auth(agent)).send({status:'In progress'}).expect(200);
 await request(app).post('/api/tickets/'+id+'/replies').set(auth(agent)).send({text:'Please try again, the report is ready.',attachments:[attachment]}).expect(201);
 await request(app).patch('/api/tickets/'+id).set(auth(agent)).send({status:'Resolved'}).expect(200);
 const ticket=(await request(app).get('/api/tickets/'+id).set(auth(customer)).expect(200)).body;
 assert.equal(ticket.status,'Resolved');assert.equal(ticket.replies.length,1);assert.equal(ticket.history.length,5);assert.equal(ticket.attachments[0].name,'evidence.txt');
 const filtered=(await request(app).get('/api/tickets?q=Cannot%20open&status=Resolved&priority=High').set(auth(customer)).expect(200)).body;
 assert.equal(filtered.total,1);assert.equal(filtered.tickets[0]._id,id);
 const second=(await request(app).get('/api/tickets?page=2').set(auth(admin)).expect(200)).body;assert.ok(second.tickets.length>0&&second.tickets.length<=6);
 await request(app).post('/api/tickets').set(auth(customer)).send({title:'Invalid file',description:'An executable attachment should be blocked.',attachments:[{name:'x.html',type:'text/html',data:'data:text/html;base64,eA=='}]}).expect(400);
});
test('registration never grants staff role and another customer cannot access a ticket',async()=>{
 const email=`new-${Date.now()}@example.com`;
 const registered=(await request(app).post('/api/auth/register').send({name:'New Customer',email,password:'DemoPassword123!',role:'admin'}).expect(201)).body;
 assert.equal(registered.user.role,'customer');assert.equal(registered.user.password,undefined);
 await request(app).get('/api/tickets/TK-1042').set(auth(registered.token)).expect(404);
 await request(app).get('/api/tickets/TK-1042').set(auth(registered.token)).expect(404);
 await request(app).post('/api/auth/login').send({email,password:'wrong-password'}).expect(401);
 await request(app).post('/api/auth/login').send({email,password:'DemoPassword123!'}).expect(200);
 await request(app).post('/api/auth/register').send({name:'Duplicate',email,password:'DemoPassword123!'}).expect(409);
});
